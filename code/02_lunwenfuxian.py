def print_band_statistics(name, band):

    print(f"\n{name}")
    print("-" * 40)

    print(f"尺寸：{band.shape}")
    print(f"最小值：{band.min():.4f}")
    print(f"最大值：{band.max():.4f}")
    print(f"平均值：{band.mean():.4f}")
    print(f"标准差：{band.std():.4f}")


