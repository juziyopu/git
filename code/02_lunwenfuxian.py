# 8. 用原图左上角一个真实 2×2 区域手工验证
# ============================================================
#
# 这是整个实验最值得你看的地方之一。
#
# 我们直接取原图：
#
#       前两行
#       前两列
#
# 得到：
#
#       a b
#       c d
#
# 然后使用刚才理论里的公式：
#
# LL = (a+b+c+d)/2
# LH = (a+b-c-d)/2
# HL = (a-b+c-d)/2
# HH = (a-b-c+d)/2
#
# 再和程序计算出来的：
#
#       LL[0,0]
#       LH[0,0]
#       HL[0,0]
#       HH[0,0]
#
# 比较。
# ============================================================

