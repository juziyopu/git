# 3. 手工实现一级二维 Haar 小波变换
# ============================================================

def haar_dwt2_level1(img):
    """
    对二维灰度图像进行一级 Haar 小波分解。

    输入
    ----------
    img : ndarray
        二维灰度图像，建议为 float 类型。

    输出
    ----------
    LL : ndarray
        低频近似子带。

    LH : ndarray
        上下方向变化对应的细节子带。

    HL : ndarray
        左右方向变化对应的细节子带。

    HH : ndarray
        对角及更复杂高频变化对应的细节子带。


    ----------------------------------------------------------
    我们本程序采用的定义：
    ----------------------------------------------------------

    对任意一个 2×2 图像块：

            a   b
            c   d

    有：

        LL = (a + b + c + d) / 2

        LH = (a + b - c - d) / 2

        HL = (a - b + c - d) / 2

        HH = (a - b - c + d) / 2

    注意：
    不同书籍、软件有时会交换 LH 与 HL 的命名，
    所以后面真正重要的是公式和方向，不只是字母名字。
    """

    rows, cols = img.shape


    # ========================================================
    # 关键检查：
    # Haar 一级下采样要求行数和列数能够两两配对。
    #
    # Set12 的 01.png 是 256×256，
    # 所以不存在这个问题。
    # ========================================================

    if rows % 2 != 0 or cols % 2 != 0:
        raise ValueError(
            "当前手工 Haar 实现要求图像高度和宽度均为偶数。"
        )


    sqrt2 = np.sqrt(2.0)


    # ========================================================
    # 第一步：沿“水平方向”做 Haar
    # ========================================================
    #
    # img[:, 0::2]
    #
    # 表示取：
    #
    # 第 0、2、4、6……列
    #
    # 即每一对像素中的左边像素。
    #
    #
    # img[:, 1::2]
    #
    # 表示取：
    #
    # 第 1、3、5、7……列
    #
    # 即每一对像素中的右边像素。
    #
    #
    # 对于：
    #
    #       x1, x2
    #
    # 低频：
    #
    #       L = (x1 + x2) / sqrt(2)
    #
    # 高频：
    #
    #       H = (x1 - x2) / sqrt(2)
    #
    # ========================================================

    left = img[:, 0::2]
    right = img[:, 1::2]

    row_low = (left + right) / sqrt2

    row_high = (left - right) / sqrt2


    # --------------------------------------------------------
    # 此时原来 256 列：
    #
    #       256
    #
    # 已经变成：
    #
    #       128 个低频系数
    #       128 个高频系数
    #
    # 所以：
    #
    # row_low.shape  = (256, 128)
    # row_high.shape = (256, 128)
    # --------------------------------------------------------


    # ========================================================
    # 第二步：对 row_low 沿垂直方向继续处理
    # ========================================================
    #
    # row_low[0::2, :]
    #
    # 取第：
    #
    #       0、2、4、6……
    #
    # 行。
    #
    # row_low[1::2, :]
    #
    # 取第：
    #
    #       1、3、5、7……
    #
    # 行。
    #
    # ========================================================

    low_top = row_low[0::2, :]
    low_bottom = row_low[1::2, :]


    # ========================================================
    # LL：
    #
    # 水平方向先低通，
    # 垂直方向再低通。
    #
    # 对应：
    #
    # LL = (a+b+c+d)/2
    #
    # 它保存图像的大尺度、整体灰度和主要轮廓。
    # ========================================================

    LL = (low_top + low_bottom) / sqrt2


    # ========================================================
    # LH：
    #
    # 水平方向低通，
    # 垂直方向高通。
    #
    # 对应：
    #
    # LH = (a+b-c-d)/2
    #
    # 本质是在比较：
    #
    #       上面一行
    #
    # 和：
    #
    #       下面一行
    #
    # 的差异。
    # ========================================================

    LH = (low_top - low_bottom) / sqrt2


    # ========================================================
    # 第三步：对 row_high 沿垂直方向继续处理
    # ========================================================

    high_top = row_high[0::2, :]
    high_bottom = row_high[1::2, :]


    # ========================================================
    # HL：
    #
    # 水平方向高通，
    # 垂直方向低通。
    #
    # 对应：
    #
    # HL = (a-b+c-d)/2
    #
    # 本质是在比较：
    #
    #       左边
    #
    # 与：
    #
    #       右边
    #
    # 的灰度差异。
    # ========================================================

    HL = (high_top + high_bottom) / sqrt2


    # ========================================================
    # HH：
    #
    # 水平方向高通，
    # 垂直方向也高通。
    #
    # 对应：
    #
    # HH = (a-b-c+d)/2
    #
    # 它更容易突出：
    #
    #       对角变化
    #       角点
    #       非规则高频结构
    #       细碎纹理
    # ========================================================

    HH = (high_top - high_bottom) / sqrt2


    return LL, LH, HL, HH


# ============================================================
# 4. 真正进行一级 Haar 分解
# ============================================================

